"""Разбор государственных номеров РК (backend/pipeline/plates.py).

Самая дорогая ошибка системы — выдуманный номер: по нему заводится чужой рейс.
Поэтому здесь два требования подряд: мусор не должен становиться номером,
а настоящий номер обязан читаться.
"""
from __future__ import annotations

import pytest

from backend.pipeline import plates
from tests.conftest import эталонные_номера

# Строки, которые OCR приносит с кадра: надпись камеры, вес на табло, обрывки цифр.
# Ни одна из них не является номером.
МУСОР = [
    ("05-06-2019", "дата с наложенной надписи камеры"),
    ("2022 0612", "дата без разделителей"),
    ("100 500 11", "цифры с табло/борта"),
    ("1234567", "просто семь цифр"),
    ("02-05-2019", "дата с кадра 1.jpg"),
    ("21:58:00", "время с наложенной надписи камеры"),
    ("09-16-2026", "дата с кадра 2.jpg"),
    ("14:22:29", "время с кадра 2.jpg"),
    ("2019 0205", "дата слитно"),
    ("12 345 67", "разбитые цифры"),
]


@pytest.mark.parametrize("строка,откуда", МУСОР, ids=[c[0] for c in МУСОР])
def test_мусор_не_становится_номером(строка, откуда):
    результат = plates.match_plate_ex(строка)
    assert результат is None, (
        f"Мусор ({откуда}) «{строка}» разобран как номер «{результат.formatted}». "
        f"Выдуманный номер хуже пустого поля: по нему заведётся чужой рейс."
    )


# Номера, названные в задании явно.
НАСТОЯЩИЕ = ["041AHF10", "384CBA10", "592LBA10", "597AQ10", "160ALV10", "681AS10", "302BL10"]


@pytest.mark.parametrize("номер", НАСТОЯЩИЕ)
def test_настоящий_номер_читается(номер):
    результат = plates.match_plate_ex(номер)
    assert результат is not None, f"Настоящий номер «{номер}» не разобран — он должен читаться."
    assert результат.compact == номер, (
        f"Номер «{номер}» прочитан как «{результат.compact}» — символы подменены при подгонке под шаблон."
    )
    assert результат.region_valid, f"Регион номера «{номер}» признан несуществующим."


@pytest.mark.parametrize("строка", ["041 AHF 10", "041ahf10", " 041AHF10 ", "KZ041AHF10", "041AHF10KZ"])
def test_номер_читается_при_любом_оформлении(строка):
    результат = plates.match_plate_ex(строка)
    assert результат is not None and результат.compact == "041AHF10", (
        f"«{строка}» должен разбираться в 041AHF10, получено: "
        f"{результат.compact if результат else 'НЕ НОМЕР'}"
    )


@pytest.mark.parametrize("кадр,номер", эталонные_номера(), ids=lambda v: str(v))
def test_номера_из_эталонной_разметки_читаются(кадр, номер):
    """Все номера, отмеченные в эталоне как читаемые, обязан разбирать и наш парсер."""
    результат = plates.match_plate_ex(номер)
    assert результат is not None, (
        f"Номер {номер} с кадра {кадр} (эталон: читаемый) не разобран — "
        f"в PLATE_TEMPLATES нет шаблона под этот формат."
    )
    assert результат.compact == номер, (
        f"Номер {номер} с кадра {кадр} прочитан как {результат.compact}: "
        f"парсер подменил символы, чтобы уложить строку в чужой шаблон."
    )


def test_номер_краской_на_борту_разбирается_как_painted():
    """«10 625 AZ» — номер, нанесённый краской: регион стоит впереди."""
    результат = plates.match_plate_ex("10 625 AZ")
    assert результат is not None, "«10 625 AZ» не разобран — это номер, нанесённый краской на борт."
    assert результат.kind == "painted", (
        f"«10 625 AZ» разобран как {результат.kind} «{результат.formatted}», "
        f"а должен быть painted: цифры 625 — не буквы."
    )
    assert результат.region == "10", f"Регион номера «10 625 AZ» — 10, получено {результат.region}."
    assert результат.formatted == "10 625 AZ", f"Ожидалось «10 625 AZ», получено «{результат.formatted}»."


@pytest.mark.parametrize("код", [f"{i:02d}" for i in range(1, 21)])
def test_коды_регионов_рк_считаются_настоящими(код):
    результат = plates.match_plate_ex(f"041AHF{код}")
    assert результат is not None, f"Номер с регионом {код} не разобран."
    assert результат.region_valid, f"Код региона {код} существует в РК, но помечен как несуществующий."


@pytest.mark.parametrize("код", ["42", "67", "00", "21", "99"])
def test_несуществующие_коды_регионов_помечаются(код):
    результат = plates.match_plate_ex(f"041AHF{код}")
    assert результат is None or not результат.region_valid, (
        f"Код региона {код} в РК не выдаётся, но номер 041AHF{код} признан полностью корректным."
    )


def test_кириллические_двойники_переводятся_в_латиницу():
    """OCR с русской моделью отдаёт кириллицу там, где на номере латиница."""
    assert plates.normalize("041АНС10") == "041AHC10", (
        "Кириллические А, Н, С имеют латинских двойников на номере и обязаны переводиться."
    )


@pytest.mark.parametrize("кириллица,латиница", [
    ("041АНС10", "041AHC10"),   # А, Н, С — кириллические двойники латинских
    ("597АQ10", "597AQ10"),
    ("625АZ10", "625AZ10"),
])
def test_похожие_кириллические_буквы_переводятся(кириллица, латиница):
    получено = plates.normalize(кириллица)
    assert получено == латиница, (
        f"normalize({кириллица!r}) = {получено!r}, ожидалось {латиница!r}: "
        f"кириллический двойник латинской буквы не переведён."
    )


@pytest.mark.parametrize("строка", ["МАЗ 5551", "041АНГ10", "041 AHФ 10", "КИРОВЕЦ"])
def test_буква_без_латинского_двойника_отвергает_строку(строка):
    """На номерах РК только латиница. Буква без двойника (З, Г, Ф) — это не номер,
    а надпись на кабине или грубая ошибка чтения. Выбрасывать её нельзя: строка
    укоротится и ляжет в шаблон ЧУЖОГО номера. Поэтому строка отвергается целиком."""
    assert plates.match_plate_ex(строка) is None, (
        f"{строка!r} разобрана как номер {plates.match_plate_ex(строка)}: "
        f"непереводимая кириллическая буква должна отвергать строку, а не исчезать из неё."
    )


def test_выброшенная_буква_не_создаёт_чужой_номер():
    """Если буква не переведена, а удалена, из 8 символов получается «номер» из 7 — чужой."""
    результат = plates.match_plate_ex("041 AHФ 10")
    if результат is not None:
        assert результат.compact != "041AH10", (
            "Из «041 AHФ 10» получился номер 041AH10: непереведённая кириллическая «Ф» "
            "просто выброшена, и строка легла в чужой шаблон. Это другой автомобиль."
        )


def test_нестрогий_разбор_для_ручного_ввода():
    """strict=False — номер вводит охранник; он видит табличку, ему верим больше, чем OCR."""
    строгий = plates.match_plate_ex("041AHF10", strict=True)
    ручной = plates.match_plate_ex("041AHF10", strict=False)
    assert строгий is not None and ручной is not None
    assert ручной.compact == "041AHF10"


def test_пустая_строка_не_номер():
    assert plates.match_plate_ex("") is None
    assert plates.match_plate_ex("   ") is None
    assert plates.match_plate("!!!") is None


def test_марка_распознаётся_по_надписи_на_технике():
    boxes = [plates.OcrBox("МАЗ", 0.8, 0, 0, 10, 10)]
    assert plates.brand_from_boxes(boxes) == "МАЗ"
    assert plates.brand_from_boxes([plates.OcrBox("KAMAZ", 0.8, 0, 0, 10, 10)]) == "КамАЗ"
    assert plates.brand_from_boxes([plates.OcrBox("ЗЕРНО", 0.8, 0, 0, 10, 10)]) is None


def test_счёт_очков_предпочитает_согласованное_прочтение():
    """Из двух прочтений побеждает то, за которое «проголосовало» больше вариантов обработки."""
    from tests.conftest import номер as сделать_номер
    уверенный = сделать_номер("041AHF10", votes=1.0, conf=0.9)
    случайный = сделать_номер("041AHF10", votes=0.2, conf=0.9)
    assert уверенный.score > случайный.score

    правленый = сделать_номер("041AHF10", votes=1.0, conf=0.9, fixes=2)
    assert уверенный.score > правленый.score, "Прочтение с правками символов не должно обгонять чистое."

    чужой_регион = сделать_номер("041AHF42", votes=1.0, conf=0.9, region="42", region_valid=False)
    assert уверенный.score > чужой_регион.score, "Номер с несуществующим регионом не должен побеждать."
