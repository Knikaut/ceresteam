"""Логика весовой: рейсы, вес, время, отмена и правка. Анализ кадра подменён заглушкой."""
from __future__ import annotations

import pytest

from backend import db
from tests.conftest import отчёт

# Время на надписи камеры: на части кадров датасета часы показывают 2019 год.
КАДР_ЗАЕЗД = "2019-05-02 21:58:00"
КАДР_ВЫЕЗД_ПОЗЖЕ = "2019-05-02 23:30:00"
КАДР_ВЫЕЗД_РАНЬШЕ = "2019-05-02 20:00:00"


def найти(предупреждения: list[str], кусок: str) -> str | None:
    return next((a for a in предупреждения if кусок.lower() in a.lower()), None)


# ---------- рейсы ----------

def test_повторная_отправка_снимка_не_создаёт_второй_рейс(весовая):
    """Оборвалась связь, весовщица нажала «Отправить» ещё раз — рейс должен остаться один."""
    capture_id = весовая.снимок(отчёт())
    первый = весовая.отправить(capture_id=capture_id)
    второй = весовая.отправить(capture_id=capture_id)

    assert второй.get("duplicate") is True, "Повторная отправка не распознана как повтор"
    assert len(db.list_trips()) == 1, f"Создано рейсов: {len(db.list_trips())}, ожидался один"
    assert первый["ai_message"]["id"] == второй["ai_message"]["id"], "Ответ ИИ продублирован в чате"


def test_заезд_потом_выезд_закрывает_рейс_и_считает_нетто(весовая):
    весовая.отправить(отчёт(timestamp=КАДР_ЗАЕЗД), weight="20")
    результат = весовая.отправить(отчёт(source_image="2.jpg", timestamp=КАДР_ВЫЕЗД_ПОЗЖЕ), seed=1, weight="8")

    рейс = db.list_trips()[0]
    assert рейс["status"] == "closed", "Рейс не закрылся на выезде"
    assert рейс["net_weight"] == 12.0, f"Нетто {рейс['net_weight']}, ожидалось 12.0 (20 − 8)"
    assert (результат["ai_message"]["payload"] or {})["event_kind"] == "exit"


def test_та_же_машина_сохраняет_бортовой_номер(весовая):
    """Номер прочитан — при следующем приезде это та же машина, а не новая."""
    весовая.отправить(отчёт(plate="041AHF10"))
    весовая.отправить(отчёт(source_image="2.jpg", plate="041AHF10"), seed=1)
    весовая.отправить(отчёт(source_image="3.jpg", plate="041AHF10"), seed=2)

    номера = [v["id"] for v in db.list_vehicles()]
    assert номера == ["1"], f"Одна машина получила бортовые номера {номера}"


# ---------- вес ----------

@pytest.mark.parametrize("введено", ["nan", "inf", "-5", "0", "абв", "5000"])
def test_негодный_вес_не_попадает_в_отчёт(весовая, введено):
    """float() принимает «nan» и «inf», а nan бесшумно ломает все сравнения весов."""
    результат = весовая.отправить(отчёт(), weight=введено)
    рейс = db.list_trips()[0]

    assert найти(весовая.предупреждения(результат), "вес"), (
        f"Вес «{введено}» принят молча, предупреждения нет"
    )
    assert рейс["entry_weight"] is not None and рейс["entry_weight"] > 0, (
        f"В базу записан вес {рейс['entry_weight']!r} из строки «{введено}»"
    )
    assert рейс["entry_weight"] == рейс["entry_weight"], "В базу попал nan"


def test_вес_из_генератора_помечен_как_непомеренный(весовая):
    """Придуманный вес нельзя показывать как показание весов: им спорят с водителем."""
    результат = весовая.отправить(отчёт())
    рейс = db.list_trips()[0]

    assert "генератор" in (рейс["entry_weight_source"] or "").lower(), (
        f"Источник веса: {рейс['entry_weight_source']!r} — не видно, что вес придуман"
    )
    assert (результат["ai_message"]["payload"] or {}).get("weight_measured") is False


def test_введённый_вес_помечен_как_ручной(весовая):
    весовая.отправить(отчёт(), weight="12,5")
    рейс = db.list_trips()[0]
    assert рейс["entry_weight"] == 12.5, "Запятая в весе не разобрана"
    assert "вручную" in (рейс["entry_weight_source"] or ""), рейс["entry_weight_source"]


def test_без_брутто_на_заезде_нетто_не_считается(весовая):
    """Старый рейс без брутто раньше подставлял ноль и давал тревогу «выезд тяжелее заезда» всегда."""
    весовая.отправить(отчёт())
    рейс_id = db.list_trips()[0]["id"]
    db.update_trip(рейс_id, entry_weight=None)

    результат = весовая.отправить(отчёт(source_image="2.jpg"), seed=1, weight="8")
    предупреждения = весовая.предупреждения(результат)

    assert найти(предупреждения, "нетто не посчитано"), предупреждения
    assert not найти(предупреждения, "тяжелее заезда"), (
        "Тревога «выезд тяжелее заезда» сработала на неизвестном брутто"
    )


# ---------- время ----------

def test_время_с_кадра_и_системное_не_сравниваются(весовая):
    """Заезд по системным часам, выезд по надписи камеры 2019 года: раньше это давало
    тревогу «время выезда раньше заезда» почти на каждом выезде."""
    весовая.отправить(отчёт(timestamp=None))
    результат = весовая.отправить(отчёт(source_image="2.jpg", timestamp=КАДР_ЗАЕЗД), seed=1)

    предупреждения = весовая.предупреждения(результат)
    assert not найти(предупреждения, "раньше времени заезда"), предупреждения
    assert not найти(предупреждения, "быстрый оборот"), предупреждения


def test_сбитые_часы_камеры_видны_когда_оба_времени_с_кадров(весовая):
    весовая.отправить(отчёт(timestamp=КАДР_ЗАЕЗД))
    результат = весовая.отправить(отчёт(source_image="2.jpg", timestamp=КАДР_ВЫЕЗД_РАНЬШЕ), seed=1)

    assert найти(весовая.предупреждения(результат), "раньше времени заезда"), (
        весовая.предупреждения(результат)
    )


def test_нормальный_оборот_по_кадрам_тревоги_не_даёт(весовая):
    весовая.отправить(отчёт(timestamp=КАДР_ЗАЕЗД))
    результат = весовая.отправить(отчёт(source_image="2.jpg", timestamp=КАДР_ВЫЕЗД_ПОЗЖЕ), seed=1)

    assert not найти(весовая.предупреждения(результат), "быстрый оборот"), (
        весовая.предупреждения(результат)
    )


def test_слишком_быстрый_оборот_по_кадрам_заметен(весовая):
    весовая.отправить(отчёт(timestamp="2019-05-02 21:58:00"))
    результат = весовая.отправить(отчёт(source_image="2.jpg", timestamp="2019-05-02 21:59:00"), seed=1)

    assert найти(весовая.предупреждения(результат), "быстрый оборот"), (
        весовая.предупреждения(результат)
    )


# ---------- отмена и правка ----------

def test_отмена_выезда_возвращает_рейс_в_открытый(весовая):
    import backend.service as service

    весовая.отправить(отчёт(timestamp=КАДР_ЗАЕЗД), weight="20")
    весовая.отправить(отчёт(source_image="2.jpg", timestamp=КАДР_ВЫЕЗД_ПОЗЖЕ), seed=1, weight="8")
    assert db.list_trips()[0]["status"] == "closed"

    service.undo_last_event()

    рейс = db.list_trips()[0]
    assert рейс["status"] == "open", "После отмены выезда рейс должен снова быть открыт"
    assert рейс["exit_weight"] is None and рейс["net_weight"] is None, "Данные выезда остались в рейсе"


def test_отмена_заезда_убирает_рейс(весовая):
    import backend.service as service

    весовая.отправить(отчёт())
    assert len(db.list_trips()) == 1

    service.undo_last_event()
    assert db.list_trips() == [], "После отмены заезда рейс остался в базе"


def test_правка_последнего_события_меняет_данные_и_остаётся_в_журнале(весовая):
    import backend.service as service

    весовая.отправить(отчёт(plate="041AHF10"), driver="Иванов", crop="Пшеница", weight="20")
    ответ = service.edit_last_event({"plate": "384 CBA 10", "driver": "Петров",
                                     "crop": "Ячмень", "weight": "18.5"})

    рейс = db.list_trips()[0]
    машина = db.list_vehicles()[0]
    assert рейс["driver"] == "Петров" and рейс["crop"] == "Ячмень"
    assert рейс["entry_weight"] == 18.5
    assert машина["plate_formatted"] == "384 CBA 10", машина
    assert ответ["changes"], "Журнал правок пуст"


def test_правка_негодным_весом_отклоняется(весовая):
    import backend.service as service

    весовая.отправить(отчёт(), weight="20")
    with pytest.raises(ValueError):
        service.edit_last_event({"weight": "nan"})
    assert db.list_trips()[0]["entry_weight"] == 20.0, "Вес испорчен неудачной правкой"
