def test_повторная_отправка_снимка_не_создаёт_второй_рейс(весовая):
    """Оборвалась связь, весовщица нажала «Отправить» ещё раз — рейс должен остаться один."""
    capture_id = весовая.снимок(отчёт())
    первый = весовая.отправить(capture_id=capture_id)
    второй = весовая.отправить(capture_id=capture_id)

    assert второй.get("duplicate") is True, "Повторная отправка не распознана как повтор"
    assert len(db.list_trips()) == 1, f"Создано рейсов: {len(db.list_trips())}, ожидался один"
    assert первый["ai_message"]["id"] == второй["ai_message"]["id"], "Ответ ИИ продублирован в чате"


def test_заезд_потом_выезд_закрывает_рейс_и_считает_нетто(весовая):
    весовая.отправить(отчёт(timestamp=КАДР_ЗАЕЗД), weight="20")
